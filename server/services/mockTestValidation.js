import { BANKING_SYLLABUS } from "../../shared/bankingSyllabus.js";
import { MIN_BANK_UPLOAD_QUESTIONS } from "./questionBankSync.js";

/**
 * Normalizes a topic label for strict case-insensitive comparison.
 */
export function normalizeTopicLabel(value = "") {
  return String(value || "")
    .trim()
    .toLowerCase()
    .replace(/\s+/g, " ");
}

/**
 * Checks whether a question's topic_name strictly matches a Topicwise Test's target topic.
 * Allows exact match (case-insensitive), plus handles canonical combined topic
 * "Simplification & Approximation" when either side uses Simplification / Approximation.
 */
export function isQuestionMatchingTopic(questionTopic, targetTopic) {
  const qNorm = normalizeTopicLabel(questionTopic);
  const tNorm = normalizeTopicLabel(targetTopic);
  if (!qNorm || !tNorm) return false;
  if (qNorm === tNorm) return true;
  if (
    tNorm === "simplification & approximation" &&
    (qNorm === "simplification" || qNorm === "approximation")
  ) {
    return true;
  }
  return false;
}

/**
 * Resolves the canonical BANKING_SYLLABUS subject entry for a given subject string.
 */
export function findSyllabusSubject(subjectName = "") {
  const needle = normalizeTopicLabel(subjectName);
  if (!needle) return null;
  return (
    BANKING_SYLLABUS.find(
      (s) =>
        normalizeTopicLabel(s.name) === needle ||
        normalizeTopicLabel(s.shortName) === needle ||
        normalizeTopicLabel(s.id) === needle ||
        (s.matchKeywords || []).some((kw) => needle.includes(kw.toLowerCase()))
    ) || null
  );
}

/**
 * Finds the best existing exam_sections row matching a given Subject name
 * so auto-generated Topicwise questions satisfy the questions.section_id FK.
 */
export async function resolveSectionForSubject(clientOrPool, subjectName) {
  const subjectObj = findSyllabusSubject(subjectName);
  const keywords = subjectObj?.matchKeywords?.length
    ? subjectObj.matchKeywords
    : [normalizeTopicLabel(subjectName)];

  const allSections = await clientOrPool.query(
    `SELECT s.id, s.name section_name, s.marks_per_correct, s.negative_marks,
            st.id stage_id, st.name stage_name, e.id exam_id, e.code exam_code, e.name exam_name, e.status exam_status
     FROM exam_sections s
     JOIN exam_stages st ON st.id = s.stage_id
     JOIN exams e ON e.id = st.exam_id
     WHERE e.status <> 'archived'
     ORDER BY CASE WHEN e.status = 'published' THEN 0 ELSE 1 END, e.sort_order ASC, st.sort_order ASC, s.sort_order ASC`
  );

  if (!allSections.rowCount) {
    return null;
  }

  const matched = allSections.rows.find((row) => {
    const secName = normalizeTopicLabel(row.section_name);
    return keywords.some((kw) => secName.includes(kw.toLowerCase()));
  });

  return matched || allSections.rows[0];
}

/**
 * Computes the next auto-incremented set_number and suggested set_label
 * for either an EXAM_WISE (examId + stageId) or TOPIC_WISE (subject + topic) test.
 */
export async function getNextSetInfo(
  clientOrPool,
  { testType = "EXAM_WISE", examId = null, stageId = null, subject = null, topic = null }
) {
  if (testType === "TOPIC_WISE") {
    const existing = await clientOrPool.query(
      `SELECT id, name, set_number, set_label, status, target_questions
       FROM mock_tests
       WHERE test_type = 'TOPIC_WISE'
         AND status <> 'archived'
         AND LOWER(subject) = LOWER($1)
         AND LOWER(topic) = LOWER($2)
       ORDER BY set_number ASC, created_at ASC`,
      [subject || "", topic || ""]
    );
    const maxSet = existing.rows.reduce(
      (max, row) => Math.max(max, Number(row.set_number || 0)),
      0
    );
    const nextSetNumber = maxSet + 1;
    return {
      nextSetNumber,
      suggestedSetLabel: `Set ${nextSetNumber}`,
      existingSets: existing.rows,
    };
  }

  const existing = await clientOrPool.query(
    `SELECT id, name, set_number, set_label, status, target_questions
     FROM mock_tests
     WHERE test_type = 'EXAM_WISE'
       AND status <> 'archived'
       AND exam_id = $1
       AND stage_id = $2
     ORDER BY set_number ASC, created_at ASC`,
    [examId, stageId]
  );
  const maxSet = existing.rows.reduce(
    (max, row) => Math.max(max, Number(row.set_number || 0)),
    0
  );
  const nextSetNumber = maxSet + 1;
  return {
    nextSetNumber,
    suggestedSetLabel: `Set ${nextSetNumber}`,
    existingSets: existing.rows,
  };
}

/**
 * Computes live section-by-section blueprint completion for an EXAM_WISE test.
 */
export async function getExamWiseBlueprintProgress(
  clientOrPool,
  { testId, stageId, durationSeconds, autoGenerated = false }
) {
  const sectionsRes = await clientOrPool.query(
    `SELECT
       s.id section_id,
       s.name section_name,
       s.question_count required_count,
       s.duration_seconds,
       count(mtq.question_id)::int assigned_count,
       count(q.id) FILTER (WHERE q.status = 'published')::int published_count
     FROM exam_sections s
     LEFT JOIN mock_test_questions mtq
       ON mtq.section_id = s.id
       AND mtq.mock_test_id = $2
     LEFT JOIN questions q ON q.id = mtq.question_id
     WHERE s.stage_id = $1
     GROUP BY s.id
     ORDER BY s.sort_order, s.name`,
    [stageId, testId]
  );

  const sections = sectionsRes.rows.map((row) => {
    const required = Number(row.required_count || 0);
    const assigned = Number(row.assigned_count || 0);
    const published = Number(row.published_count || 0);
    const missing = Math.max(0, required - published);
    const excess = Math.max(0, assigned - required);
    return {
      sectionId: row.section_id,
      sectionName: row.section_name,
      required,
      assigned,
      published,
      missing,
      excess,
      durationSeconds: row.duration_seconds === null ? null : Number(row.duration_seconds),
      complete: required > 0 && assigned === required && published === required,
    };
  });

  const totalRequired = sections.reduce((sum, s) => sum + s.required, 0);
  const totalAssigned = sections.reduce((sum, s) => sum + s.assigned, 0);
  const totalPublished = sections.reduce((sum, s) => sum + s.published, 0);

  const hasSectionalTimers = sections.some((s) => s.durationSeconds !== null);
  const sectionalTimerSum = sections.reduce(
    (sum, s) => sum + (s.durationSeconds ?? 0),
    0
  );
  const allSectionalTimersPresent = sections.every((s) => s.durationSeconds !== null && s.durationSeconds > 0);
  const sectionalTimersValid =
    !hasSectionalTimers || (allSectionalTimersPresent && sectionalTimerSum > 0);

  const sectionsComplete =
    sections.length > 0 && sections.every((s) => s.complete);

  const isComplete = autoGenerated
    ? totalPublished >= MIN_BANK_UPLOAD_QUESTIONS
    : sectionsComplete && sectionalTimersValid;

  return {
    totalRequired,
    totalAssigned,
    totalPublished,
    hasSectionalTimers,
    sectionalTimerSum,
    sectionalTimersValid,
    sectionsComplete,
    isComplete,
    sections,
  };
}

/**
 * Strict Publish Validation Rule Engine for BOTH Topicwise & Exam Wise Tests.
 * Returns { ok: true, test, progress } or { ok: false, statusCode, error, details }.
 */
export async function validateTestForPublish(clientOrPool, testId) {
  const testRes = await clientOrPool.query(
    `SELECT
       t.id, t.test_type, t.name, t.exam_id, t.stage_id, t.subject, t.topic,
       t.set_number, t.set_label, t.target_questions, t.duration_seconds,
       t.auto_generated, t.status,
       e.status exam_status, e.name exam_name, st.name stage_name
     FROM mock_tests t
     LEFT JOIN exams e ON e.id = t.exam_id
     LEFT JOIN exam_stages st ON st.id = t.stage_id
     WHERE t.id = $1`,
    [testId]
  );

  if (!testRes.rowCount) {
    return {
      ok: false,
      statusCode: 404,
      error: "Mock test not found.",
    };
  }

  const test = testRes.rows[0];

  // ========================================================================
  // RULE A: TOPIC_WISE Publish Validation
  // ========================================================================
  if (test.test_type === "TOPIC_WISE") {
    const target = Number(test.target_questions || 0);
    if (target <= 0) {
      return {
        ok: false,
        statusCode: 400,
        error: "Cannot publish: configure a target question count greater than 0.",
        details: { testType: "TOPIC_WISE", target, assigned: 0 },
      };
    }

    const assignedRes = await clientOrPool.query(
      `SELECT q.id, q.topic_name, q.status
       FROM mock_test_questions mtq
       JOIN questions q ON q.id = mtq.question_id
       WHERE mtq.mock_test_id = $1`,
      [testId]
    );

    const allRows = assignedRes.rows;
    const publishedRows = allRows.filter((q) => q.status === "published");
    const offTopicRows = publishedRows.filter(
      (q) => !isQuestionMatchingTopic(q.topic_name, test.topic)
    );

    if (offTopicRows.length > 0) {
      return {
        ok: false,
        statusCode: 400,
        error: `Cannot publish: ${offTopicRows.length} assigned question(s) do not belong to topic "${test.topic}".`,
        details: {
          testType: "TOPIC_WISE",
          topic: test.topic,
          target,
          assigned: publishedRows.length,
          offTopicCount: offTopicRows.length,
        },
      };
    }

    if (publishedRows.length !== target) {
      const diff = target - publishedRows.length;
      const hint =
        diff > 0
          ? `${diff} more needed`
          : `${Math.abs(diff)} excess question(s) must be removed`;
      return {
        ok: false,
        statusCode: 400,
        error: `Cannot publish: ${publishedRows.length} of ${target} questions added (${hint}).`,
        details: {
          testType: "TOPIC_WISE",
          topic: test.topic,
          target,
          assigned: publishedRows.length,
          missing: Math.max(0, diff),
        },
      };
    }

    return {
      ok: true,
      test,
      progress: {
        testType: "TOPIC_WISE",
        target,
        assigned: publishedRows.length,
        isComplete: true,
      },
    };
  }

  // ========================================================================
  // RULE B: EXAM_WISE Publish Validation (Strict Blueprint Check)
  // ========================================================================
  if (test.exam_status !== "published") {
    return {
      ok: false,
      statusCode: 409,
      error:
        "Publish the examination after verifying its official pattern before publishing this test.",
      details: { testType: "EXAM_WISE", examStatus: test.exam_status },
    };
  }

  const progress = await getExamWiseBlueprintProgress(clientOrPool, {
    testId: test.id,
    stageId: test.stage_id,
    durationSeconds: test.duration_seconds,
    autoGenerated: Boolean(test.auto_generated),
  });

  if (test.auto_generated) {
    if (progress.totalPublished < MIN_BANK_UPLOAD_QUESTIONS) {
      return {
        ok: false,
        statusCode: 400,
        error: `Cannot publish: ${progress.totalPublished}/${MIN_BANK_UPLOAD_QUESTIONS} published questions added — upload at least ${MIN_BANK_UPLOAD_QUESTIONS} published questions to publish this Question Bank mock test.`,
        details: { testType: "EXAM_WISE", progress },
      };
    }
    return { ok: true, test, progress };
  }

  if (!progress.sections.length) {
    return {
      ok: false,
      statusCode: 400,
      error: "Cannot publish: this exam stage has no configured blueprint sections.",
      details: { testType: "EXAM_WISE", progress },
    };
  }

  if (!progress.sectionsComplete) {
    const incompleteDetails = progress.sections
      .filter((s) => !s.complete)
      .map((s) =>
        s.required <= 0
          ? `${s.sectionName}: blueprint question count not set`
          : s.published < s.required
          ? `${s.sectionName}: ${s.published}/${s.required} (${s.required - s.published} more needed)`
          : `${s.sectionName}: ${s.assigned}/${s.required} (${s.assigned - s.required} extra)`
      )
      .join("; ");

    return {
      ok: false,
      statusCode: 400,
      error: `Cannot publish: ${progress.totalPublished}/${progress.totalRequired} questions added — complete all sections before publishing (${incompleteDetails}).`,
      details: { testType: "EXAM_WISE", progress },
    };
  }

  if (!progress.sectionalTimersValid) {
    return {
      ok: false,
      statusCode: 400,
      error:
        "Cannot publish: configure a sectional duration for every section in Exam setup.",
      details: { testType: "EXAM_WISE", progress },
    };
  }

  // Guarantee mock_tests.duration_seconds can never mismatch its sectional timer sum
  if (
    progress.hasSectionalTimers &&
    progress.sectionalTimerSum > 0 &&
    Number(test.duration_seconds) !== progress.sectionalTimerSum
  ) {
    await clientOrPool.query(
      "UPDATE mock_tests SET duration_seconds = $1, updated_at = NOW() WHERE id = $2",
      [progress.sectionalTimerSum, test.id]
    );
    test.duration_seconds = progress.sectionalTimerSum;
  }

  return { ok: true, test, progress };
}
